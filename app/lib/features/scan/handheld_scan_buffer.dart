import 'package:flutter/services.dart';

/// รวมคีย์จากเครื่องยิงบาร์โค้ด (handheld) ให้กลายเป็น "รหัสเดียว"
///
/// เครื่องยิงเกือบทุกรุ่นทำตัวเป็นคีย์บอร์ด (HID keyboard-wedge): ยิงหนึ่งครั้ง =
/// พิมพ์อักขระรหัสรัว ๆ แล้วปิดท้ายด้วย Enter — ไม่ใช่เหตุการณ์ "สแกน" ที่ Flutter
/// รู้จัก เราจึงต้องรวมคีย์เอง แล้วตัดสินว่าจบรหัสเมื่อเจอ Enter
///
/// แยกออกมาเป็นคลาสล้วน ๆ (ไม่พึ่ง widget) เพื่อให้เขียนเทสต์ครอบพฤติกรรมได้ตรง ๆ
/// โดยไม่ต้อง pump ทั้งจอ และเพื่อให้ **เวลา** ถูกส่งเข้ามาจากผู้เรียก ไม่ใช่อ่าน
/// นาฬิกาเอง — เทสต์จึงคุมจังหวะได้ 100%
///
/// [feed] เป็น **แหล่งความจริงเดียว** ทั้งเรื่อง "รหัสจบหรือยัง" และ "คีย์นี้ถูก
/// กลืนไปแล้วหรือไม่" — ไม่มี predicate แยกไว้ให้ผู้เรียกถามซ้ำ เพราะสองฝั่งจะ
/// เบี่ยงจากกันเงียบ ๆ ได้ (เคยพลาดมาแล้วกับ Enter เปล่า ๆ ที่ถูกตัดสินคนละแบบ)
///
/// **กลืนคีย์ตามความเร็ว ไม่ใช่ตาม "เข้าบัฟเฟอร์แล้ว"** — บน Android คีย์บอร์ดจอ
/// แบบตัวเลขส่งเลขที่แตะผ่าน `InputConnection.sendKeyEvent()` ซึ่งวิ่งมาทาง
/// `KeyboardManager` เส้นเดียวกับคีย์ฮาร์ดแวร์ ถ้ากลืนเพราะ "บัฟเฟอร์รับไว้แล้ว"
/// เลขที่คนแตะจะหายเงียบ ๆ จากช่องจำนวนนับ · ตัวแยกคือ **จังหวะ**: เครื่องยิงส่ง
/// อักขระห่างกันระดับสิบมิลลิวินาที นิ้วคนไม่มีทางเร็วขนาดนั้น (ดู [burstGap])
///
/// ⚠️ **คลาสนี้ทั้งคลาสไม่ถูกใช้เลยบนเครื่องที่ตั้งเป็นเส้นทาง intent** — Bluebird
/// S20 หน้างานถูกตั้งให้ส่งผลอ่านเป็น broadcast ของ BBAPI (ดู `BluebirdScanChannel`)
/// บาร์โค้ดจึงไม่เคยกลายเป็นคีย์สักตัว ไม่มีอะไรไหลเข้า [feed] ไม่มีสายรัวให้ตรวจ
/// ไม่มีอักขระรั่วลงช่องจำนวน และตาข่าย snapshot/restore ของจอสแกนก็ไม่เคยทำงาน
///
/// **ห้ามถอดทิ้งเพราะเหตุนี้**: เครื่องในคลังไม่ได้ตั้งค่าเหมือนกันทุกตัว ตัวที่ยัง
/// เป็น keyboard wedge อยู่พึ่งคลาสนี้ทั้งหมด และการตั้งค่านั้นสลับได้ที่ตัวเครื่อง
/// โดยไม่ต้องลงแอปใหม่ — สองเส้นทางต้องอยู่พร้อมกันได้เสมอ
///
/// Invariant: `_burst == true` ⇔ เห็นอักขระ [burstMinRun] ตัว**ติดกัน** ที่ห่างกัน
/// ไม่เกิน [burstGap] ภายในรหัสที่กำลังไหลอยู่ตอนนี้ และรหัสนั้นยังไม่จบ ยังไม่มี
/// ช่องไฟเกิน [burstHold] มาคั่น และยังไม่ถูก [reset] — `_burst` เหนียวได้ในกรอบ
/// [burstHold] เท่านั้น: จังหวะสะดุดกลางรหัสไม่ทำให้อักขระที่เหลือรั่วออกไป
/// แต่คนที่หันมาแตะจอหลังยิงเสร็จก็ไม่ถูกนับเป็นเครื่องอีกต่อไป
///
/// ⚠️ **ช่องไฟตัวเดียวไม่พอ (บทเรียนหน้างาน 5 ก.ย. 2569)** — เดิม `_burst` เป็นจริง
/// ทันทีที่เห็นอักขระ**สองตัว**ห่างกัน ≤ [burstGap] แล้วเหนียวยาวถึง [idleReset]
/// 800ms ผลคือนิ้วคนที่แตะเลขสองตัวติดกันเร็วหน่อย (หรือแตะภายใน 800ms หลังยิง)
/// ถูกตัดสินว่าเป็นเครื่อง แล้วตาข่ายกู้ยอดก็ถอยเลขที่พนักงานเพิ่งคีย์กลับเงียบ ๆ
/// = "Clear text เพื่อกรอกใหม่ไม่ได้" · หลักฐานที่พิสูจน์เครื่องจักรได้จริงคือ
/// **ความยาวของสายที่เร็วติดกัน** ไม่ใช่ช่องไฟช่องเดียว
class HandheldScanBuffer {
  HandheldScanBuffer({
    this.idleReset = const Duration(milliseconds: 800),
    this.burstGap = defaultBurstGap,
    this.burstHold = defaultBurstHold,
    this.burstMinRun = defaultBurstMinRun,
    this.maxLength = 64,
    HandheldGapLog? gapLog,
  }) : gapLog = gapLog ?? HandheldGapLog.shared;

  /// เงียบนานกว่านี้ = สายรัวที่ไม่มี Enter ปิดท้าย "ตายไปเฉย ๆ"
  ///
  /// ⚠️ **ไม่ใช่เกณฑ์ความต่อเนื่องของรหัสอีกต่อไป** — งานนั้นย้ายไป [burstHold]
  /// ซึ่งสั้นกว่ามาก (เดิมใช้ตัวนี้ตัวเดียวทำสองหน้าที่ ผลคือเลขที่พนักงานคีย์
  /// ค้างในบัฟเฟอร์ได้นานถึง 800ms แล้วไปเกาะหน้าบาร์โค้ดใบถัดไป)
  ///
  /// ที่นี่เหลือสองหน้าที่: กรอบเวลาที่ [HandheldGapLog] ยอมจด (เกินกว่านี้คือเวลา
  /// ที่คนเดินไปหยิบของ ไม่ใช่จังหวะเครื่อง) และเส้นตายของตาข่ายกู้ยอดฝั่งจอ
  /// ซึ่งอ่านค่านี้ไปใช้ตรง ๆ (`_burstDeath` ใน `scan_screen.dart`)
  final Duration idleReset;

  /// ค่าปริยายของ [burstGap] — จุดเดียวที่ตัวเลขนี้มีอยู่ทั้งแอป
  /// (จอผู้ดูแลอ่านค่านี้ไปเทียบกับจังหวะที่วัดได้จริง ห้ามพิมพ์ซ้ำที่นั่น)
  static const Duration defaultBurstGap = Duration(milliseconds: 70);

  /// อักขระที่ห่างกันไม่เกินนี้ = มาจากเครื่องจักร ไม่ใช่นิ้วคน
  ///
  /// ⚠️ **ยังไม่เคยวัดกับ Bluebird S20 (SE4710) ตัวจริง** — ค่านี้จึงเลือกให้
  /// "ผิดแล้วยังไม่พัง" ไม่ใช่ให้พอดีเป๊ะ ตัวเลขที่ใช้ตั้งเกณฑ์:
  /// - ฝั่งเครื่อง: SE4710 ผ่าน HID keyboard-wedge ส่งราว **10-30ms/อักขระ**
  ///   (ควอนไทซ์ตาม HID polling ~8ms) และไม่คงที่ — GC/เฟรมตกบวก jitter เข้ามาได้
  /// - ฝั่งคน: แตะคีย์บอร์ดจอติด ๆ กันเร็วที่สุดแบบต่อเนื่องยัง **เกิน 100ms**
  ///
  /// 70ms = **2.3 เท่า**ของขอบบนฝั่งเครื่อง (30ms) และยังต่ำกว่าขอบล่างฝั่งคน
  /// (100ms) อยู่ **30ms** — เหลือที่ทั้งสองข้าง ไม่ชิดข้างใดข้างหนึ่ง
  /// (60ms เดิมอ้างฝั่งเครื่องไว้ที่ 5-20ms ซึ่งมองข้าม jitter ของ HID wedge จริง)
  ///
  /// ⚠️ **ไม่ใช่ด่านเดียวอีกต่อไป** — ช่องไฟช่องเดียวที่บังเอิญแคบไม่พอพิสูจน์
  /// อะไรแล้ว ต้องผ่าน [burstMinRun] ด้วย (บทเรียนหน้างาน 5 ก.ย. 2569 ที่หัวคลาส)
  ///
  /// ⚠️ เกณฑ์นี้ **ผิดได้ทั้งสองทาง และเจ็บทั้งสองทาง** — เดิมเข้าใจว่าผิดต่ำ
  /// ปลอดภัยกว่าเพราะ restore กู้ให้ ซึ่ง**ไม่จริง**:
  /// - สูงไป → คีย์ที่นิ้วคนแตะถูกตัดสินว่าเป็นเครื่อง = ถูกกลืน เลขหายจากช่อง
  ///   แล้วเส้นตายกู้ยังถอยยอดที่เพิ่งคีย์กลับให้อีกดอก
  /// - ต่ำไป → `_burst` ไม่มีวันเป็น true: ไม่กลืน (พอทน) แต่ `_armBurstDeath`
  ///   ไม่ติด และ `_closeCountSnapshot` "ทิ้ง" แทน "กู้" = **ตาข่ายกู้ยอดทั้งชุด
  ///   เปิดโล่งเงียบ ๆ** บั๊กยอดเพี้ยนเดิมกลับมาเต็มรูปแบบโดยไม่มีสัญญาณอะไรเลย
  ///
  /// เป็น named parameter เพื่อให้ปรับหน้างานได้โดยไม่ต้องแตะตรรกะ · ค่าที่วัดได้
  /// จริงอ่านจาก [HandheldGapLog] (จอผู้ดูแล → แท็บ "ปุ่มเครื่อง")
  final Duration burstGap;

  /// ค่าปริยายของ [burstHold] — ขอบเขตความ "เหนียว" ของสายรัวที่พิสูจน์แล้ว
  static const Duration defaultBurstHold = Duration(milliseconds: 250);

  /// ช่องไฟที่ยาวกว่านี้ = อักขระตัวนี้ **ไม่ได้อยู่ในรหัสเดียวกับที่ค้างอยู่**
  ///
  /// ทำสองอย่างพร้อมกัน เพราะมันคือข้อสรุปเดียวกัน ("สายเก่าจบไปแล้ว"):
  /// 1. ทิ้งอักขระที่ค้าง — เลขที่พนักงานเพิ่งคีย์ลงช่องจำนวนต้องไม่ไปเกาะหน้า
  ///    บาร์โค้ดของใบถัดไป (หน้างาน 5 ก.ย.: คีย์ "19" แล้วเหนี่ยวไกทันที รหัสที่
  ///    ส่งไปค้นกลายเป็น `19` + บาร์โค้ด → ไม่พบสินค้า ใบที่สองไม่ขึ้นการ์ดเลย)
  /// 2. ล้างสถานะสายรัว — คีย์ของคนหลังจากนั้นต้องไม่ถูกกลืน
  ///
  /// **ต่างจาก [idleReset] คนละหน้าที่**: [idleReset] คือเส้นตายของ "ตาข่ายกู้ยอด"
  /// ฝั่งจอ (เงียบนานเท่านี้ = สายรัวตายไปเฉย ๆ ต้องกู้ช่องคืน) ส่วนตัวนี้คือ
  /// เกณฑ์ **ความต่อเนื่องของรหัส** ซึ่งต้องสั้นกว่ามาก
  ///
  /// ตัวเลข 250ms เลือกจากขอบทั้งสองฝั่ง:
  /// - ฝั่งเครื่อง: HID wedge ส่ง 10-30ms/อักขระ ช่องไฟเดียวที่ยืดได้จริงคือ
  ///   ตอนไอโซเลตถูกบล็อก (GC/เฟรมหนัก) ซึ่งวัดได้ระดับ ~100ms — 250ms คือ
  ///   **8 เท่า**ของขอบบนปกติ และยังเผื่อสะดุดหนักไว้อีกเท่าตัว
  /// - ฝั่งคน: เร็วที่สุดที่คนหันมาแตะจอหลังเสียงบี๊บยังเกิน 300ms
  ///
  /// ⚠️ ผิดฝั่งสูง = เลขที่พนักงานคีย์ไปเกาะหน้าบาร์โค้ดใบถัดไป (บั๊กที่กำลังแก้)
  ///    ผิดฝั่งต่ำ = บาร์โค้ดที่สะดุดกลางคันถูกหั่นเป็นสองท่อน → "ไม่พบสินค้า"
  ///    ซึ่งพนักงาน**เห็น**และยิงซ้ำได้ ต่างจากยอดที่เพี้ยนเงียบ ๆ
  final Duration burstHold;

  /// ค่าปริยายของ [burstMinRun] — จำนวนอักขระที่ต้องเห็นก่อนเชื่อว่าเป็นเครื่อง
  static const int defaultBurstMinRun = 4;

  /// อักขระ **ติดกันกี่ตัว** ที่ห่างกันไม่เกิน [burstGap] ถึงจะถือว่าพิสูจน์
  /// "สายรัวของเครื่องยิง" ได้
  ///
  /// ช่องไฟช่องเดียว (อักขระสองตัว) พิสูจน์ไม่ได้ — นิ้วคนที่รีบแตะเลขสองตัวติดกัน
  /// บนแป้นตัวเลขของเครื่องก็ทำได้ และผลของการเดาผิดตรงนั้นคือยอดที่พนักงานคีย์
  /// หายไปเอง (ดูหัวคลาส)
  ///
  /// 4 มาจากช่องว่างระหว่างสองฝั่งที่กว้างที่สุดเท่าที่หาได้:
  /// - ฝั่งคน: 4 อักขระโดยมีช่องไฟ ≤70ms **สามช่องติดกัน** = พิมพ์เกิน 14 ตัว/วินาที
  ///   ต่อเนื่อง ซึ่งเกินขีดของนิ้วบนปุ่มคนละปุ่ม · และยอดที่นับกันจริงยาว 1-3 หลัก
  /// - ฝั่งเครื่อง: บาร์โค้ดที่คลังใช้สั้นสุดคือ SKU แบบ `2010201` (7 ตัว) และ
  ///   EAN-8/EAN-13 (8/13 ตัว) — พิสูจน์เสร็จตั้งแต่ตัวที่ 4 ยังเหลืออีกครึ่งสาย
  ///   ให้กลืน และเสร็จภายใน ~30-90ms หลังเหนี่ยวไก (เร็วกว่าเส้นตายกู้ยอดมาก)
  ///
  /// ราคาที่จ่าย: อักขระ [burstMinRun] − 1 ตัวแรกของทุกการยิง "รั่ว" ลงช่องที่
  /// โฟกัสอยู่ (เดิมรั่วตัวเดียว) — ตาข่าย snapshot/restore ถอนคืนให้ทั้งหมด
  /// เพราะ snapshot ถูกเก็บก่อนตัวแรกเสมอ ดู `snapshotNow`
  final int burstMinRun;

  /// สมุดจดช่องไฟที่วัดได้ — **วินิจฉัยอย่างเดียว ไม่มีผลต่อการตัดสินใจใด ๆ**
  final HandheldGapLog gapLog;

  /// กันบัฟเฟอร์บวมเมื่อมีอะไรพิมพ์รัวเข้ามาโดยไม่มี Enter สักที
  /// บาร์โค้ดจริงยาวไม่เกินนี้ (EAN-13 = 13 · Code128 ทั่วไป < 30)
  final int maxLength;

  final StringBuffer _chars = StringBuffer();
  DateTime? _lastAt;
  bool _burst = false;

  /// อักขระที่เร็วระดับเครื่องจักร **ติดกัน**กี่ตัวแล้ว ณ ตอนนี้ (นับรวมตัวแรก
  /// ของสาย) — ตัวนับที่ทำให้ [burstMinRun] มีความหมาย
  int _run = 0;

  /// อักขระที่ค้างอยู่ตอนนี้ — มีไว้ให้เทสต์และ debug ตรวจสถานะ
  String get pending => _chars.toString();

  /// กำลังอยู่ในสายรัวของเครื่องยิงหรือไม่ — มีไว้ให้เทสต์/debug อ่านเหมือน [pending]
  bool get inBurst => _burst;

  /// คีย์ที่ไม่เกี่ยวกับเครื่องยิงเลย — ไม่กลืน ไม่ต้อง snapshot ไม่จบรหัส
  static const ({bool swallow, bool snapshotNow, String? code}) _ignored =
      (swallow: false, snapshotNow: false, code: null);

  /// ป้อนหนึ่งเหตุการณ์คีย์ · คืนสามอย่างพร้อมกันในค่าเดียว
  ///
  /// - `swallow` = ผู้เรียกต้องตอบ `KeyEventResult.handled` · **จริงเฉพาะเมื่ออยู่ใน
  ///   สายรัวที่พิสูจน์แล้ว** ([burstMinRun] ตัวติดกันที่เร็วระดับเครื่อง) เลขที่คน
  ///   แตะบนแป้นตัวเลขจึงไม่มีวันถูกกลืน
  /// - `snapshotNow` = คีย์ตัวนี้ **เปิดรหัสใหม่** และกำลังจะรั่วลงช่องที่โฟกัสอยู่
  ///   ผู้เรียกต้องเก็บ snapshot ของช่องนั้น **ก่อน** คืนค่า
  /// - `code` = **รหัสที่จบแล้ว** เมื่อเจอ Enter · `null` = ยังไม่จบ
  ///
  /// จังหวะที่บังคับรูปนี้: `_onHandheldKey` ทำงาน **ก่อน** เอนจินเขียนอักขระลงช่อง
  /// กว่าจะพิสูจน์สายรัวได้ อักขระตัวแรก ๆ ก็รั่วไปแล้ว — snapshot จึงต้องถูกเก็บที่
  /// **ตัวที่เปิดรหัส** (ตัวแรกสุดที่ยังไม่มีอะไรรั่ว) ตัวเดียว ไม่ใช่ทุกตัวที่ยัง
  /// พิสูจน์ไม่ได้ ไม่งั้นตัวที่ 2..[burstMinRun]−1 ซึ่งรั่วไปแล้วจะทับ snapshot ที่ดี
  /// · อักขระจากนิ้วคนก็สั่ง snapshot ด้วย (แยกไม่ออก ณ ตัวแรก) แต่ snapshot นั้น
  /// ไม่มีวันถูกใช้ เพราะทางกู้ทุกทางต้องมีสายรัวที่พิสูจน์แล้วเป็นด่าน
  ///
  /// เลิกคืน `consumed` แล้ว — ไม่เก็บไว้คู่กับ `swallow` เพราะผู้เรียกเดียวที่ใช้มัน
  /// ใช้เพื่อตัดสิน `handled` พอดี การมีสองตัวคือการสร้าง predicate ซ้ำที่หัวคลาสห้ามไว้
  ///
  /// คีย์ที่ไม่ใช่ของเครื่องยิง (ปุ่มไม่มี character, Enter บนบัฟเฟอร์ว่าง) คืน
  /// [_ignored] และ **ไม่แตะ `_lastAt`** — ไม่งั้นมันจะไปยืดหน้าต่าง idle-reset
  /// ให้เศษรหัสที่ค้างอยู่รอดต่อไปทั้งที่ไม่ได้ยิงอะไรเพิ่มเลย
  ///
  /// [now] ส่งเข้ามาจากผู้เรียกเสมอ (ดูเหตุผลที่หัวคลาส)
  ({bool swallow, bool snapshotNow, String? code}) feed(
    KeyEvent event, {
    required DateTime now,
  }) {
    // สนใจเฉพาะตอนกดลง — KeyUpEvent/KeyRepeatEvent จะทำให้ได้อักขระซ้ำสองเท่า
    if (event is! KeyDownEvent) return _ignored;

    final key = event.logicalKey;
    if (key == LogicalKeyboardKey.enter || key == LogicalKeyboardKey.numpadEnter) {
      // Enter ตอนไม่มีอะไรค้าง = ไม่ได้จบรหัสอะไรทั้งนั้น อาจมาจากคีย์บอร์ดจริง
      // หรือปุ่มข้างที่บังเอิญส่ง Enter — ต้องปล่อยผ่าน ไม่ใช่กลืนเงียบ ๆ
      if (_chars.isEmpty) return _ignored;
      final swallow = _burst; // Enter ที่ปิดท้ายสายรัวเท่านั้นที่กลืน
      _lastAt = now;
      final code = _chars.toString().trim();
      _chars.clear();
      _burst = false; // รหัสจบ = สายรัวจบ
      _run = 0; // รหัสหน้าต้องพิสูจน์ตัวเองใหม่ ไม่สืบทอดหลักฐานของใบก่อน
      return (
        swallow: swallow,
        snapshotNow: false,
        code: code.isEmpty ? null : code,
      );
    }

    // อักขระพิมพ์ได้เท่านั้น — ตัด modifier/ลูกศร/ฟังก์ชันคีย์ที่ character เป็น null
    // (รวมปุ่มฮาร์ดแวร์ที่ผูกไว้กับการสลับโหมด) ปุ่มพวกนี้ไม่ใช่ของเครื่องยิง
    final ch = event.character;
    if (ch == null || ch.length != 1) return _ignored;

    final last = _lastAt;
    final gap = last == null ? null : now.difference(last);
    // จดไว้ให้ช่างอ่าน — เฉพาะช่องไฟ "ภายในการยิงเดียวกัน" (เกิน idleReset
    // คือเวลาที่คนเดินไปหยิบของ ไม่ใช่จังหวะของเครื่อง) · หนึ่ง add ต่อคีย์
    // ไม่มีใครอ่านค่านี้กลับมาตัดสินอะไร ถอดทิ้งแล้วพฤติกรรมสแกนเท่าเดิมเป๊ะ
    if (gap != null && gap <= idleReset) gapLog.record(gap.inMilliseconds);

    if (gap == null || gap > burstHold) {
      // ห่างเกินกว่าจะเป็นอักขระถัดไปของรหัสเดิม = อักขระตัวนี้ **เปิดรหัสใหม่**
      // เศษที่ค้าง (รวมเลขที่คนคีย์ลงช่องจำนวน) ต้องไม่ไปเกาะหน้ารหัสใหม่
      _chars.clear();
      _burst = false;
      _run = 1;
    } else if (gap <= burstGap) {
      // เร็วระดับเครื่องจักร — สะสมหลักฐาน ครบ burstMinRun เมื่อไรจึงเชื่อ
      _run++;
      if (_run >= burstMinRun) _burst = true;
    } else {
      // ช้ากว่าเครื่องแต่ยังไม่ขาดตอน (เฟรมตก/GC) — สายที่ **พิสูจน์แล้ว** รอด
      // สะดุดไปได้ตามเดิม แต่หลักฐานที่ยังสะสมไม่ครบต้องเริ่มนับใหม่
      _run = 1;
    }
    _lastAt = now;

    // อักขระตัวนี้เปิดรหัสใหม่หรือไม่ — **ต้องอ่านหลังการล้างข้างบน ก่อนการเขียน**
    //
    // นี่คือจังหวะเดียวที่ควรสั่ง snapshot: ค่าที่อยู่ในช่องตอนนี้คือค่าก่อนที่
    // อักขระตัวแรกของการยิงจะรั่วลงไป · เดิมสั่งที่ "ทุกตัวที่ยังไม่อยู่ในสายรัว"
    // ซึ่งกว้างเกินไป — อักขระตัวที่ 2..burstMinRun-1 ที่รั่วไปแล้วจะทับ snapshot
    // ที่ดีทิ้ง แล้วการกู้ก็กู้ได้ไม่หมด
    final opensCode = _chars.isEmpty;

    // อักขระควบคุม (< 0x20) ที่บางรุ่นแทรกมาเป็น prefix/suffix — ไม่ใช่เนื้อรหัส
    // แต่กลืน/snapshot ตามสถานะสายรัวเหมือนอักขระอื่น
    if (ch.codeUnitAt(0) < 0x20) {
      return (swallow: _burst, snapshotNow: opensCode, code: null);
    }

    // ⚠️ ล้างเพราะยาวเกินเพดาน แต่ **ไม่แตะ `_burst`** — สายเดิมยังไหลอยู่
    if (_chars.length >= maxLength) _chars.clear();
    _chars.write(ch);
    return (swallow: _burst, snapshotNow: opensCode, code: null);
  }

  /// ทิ้งอักขระที่ค้าง — เรียกเมื่อออกจากจอหรือสลับโหมด
  void reset() {
    _chars.clear();
    _lastAt = null;
    _burst = false;
    _run = 0;
  }
}

/// ช่องไฟระหว่างอักขระที่ **วัดได้จริง** ครั้งล่าสุด — วินิจฉัยอย่างเดียว
///
/// [HandheldScanBuffer.burstGap] เป็นค่าที่เดาจากสเปก ไม่ใช่ค่าที่วัด และมันคือ
/// เสาเดียวที่ค้ำด่านป้องกันทั้งสองชั้น เดาผิดฝั่งต่ำ = ตาข่ายเปิดโล่งเงียบ ๆ
/// สมุดเล่มนี้ทำให้การวัดหน้างานเป็นการ **อ่านค่า** ไม่ใช่การเดารอบสอง:
/// ยิงบาร์โค้ดสักสิบใบ แล้วเปิดจอผู้ดูแล → แท็บ "ปุ่มเครื่อง" อ่านค่าสูงสุด
/// ถ้าค่าสูงสุดขยับเข้าใกล้เกณฑ์ แปลว่าเกณฑ์เตี้ยไปสำหรับเครื่องรุ่นนั้น
///
/// อยู่นอก [HandheldScanBuffer] เพราะบัฟเฟอร์ตายไปพร้อมจอสแกนทุกครั้งที่สลับแท็บ
/// (ไม่มี `IndexedStack` คั่น) ค่าที่วัดได้จึงต้องรอดข้ามแท็บถึงจะเอาไปอ่านได้
class HandheldGapLog {
  HandheldGapLog();

  /// เล่มที่จอผู้ดูแลอ่าน — บัฟเฟอร์ทุกตัวที่ไม่ระบุเล่มเองจะจดลงเล่มนี้
  static final HandheldGapLog shared = HandheldGapLog();

  /// พอเห็นการยิงหลายใบติดกัน (EAN-13 = 12 ช่องไฟต่อใบ) โดยจอไม่ยาวไม่รู้จบ
  static const int capacity = 40;

  final List<int> _ms = [];

  /// ค่าที่จดไว้ เรียงเก่า → ใหม่ (มิลลิวินาที)
  List<int> get gaps => List.unmodifiable(_ms);

  /// จดหนึ่งค่า — O(1) ตามอายุการใช้งานจริง (ลิสต์ยาวไม่เกิน [capacity])
  void record(int ms) {
    _ms.add(ms);
    if (_ms.length > capacity) _ms.removeAt(0);
  }

  /// เริ่มวัดรอบใหม่ — ช่างกดก่อนยิงชุดที่จะใช้เป็นผลวัดจริง
  void clear() => _ms.clear();
}
